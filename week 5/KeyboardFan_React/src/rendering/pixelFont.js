export function drawPixelText(ctx, text, x, y) {
  ctx.fillStyle = "#000";
  [...text.toUpperCase()].forEach((char, i) => {
    const glyph = GLYPHS[char] || GLYPHS[' '];
    glyph.forEach((row, ry) => [...row].forEach((bit, rx) => {
      if (bit === "1") ctx.fillRect(x + i * 6 + rx, y + ry, 1, 1);
    }));
  });
}
